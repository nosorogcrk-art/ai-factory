#!/bin/bash
# Полная структура папок согласно спецификации P0.3.1
DIRS=(
  "00_КАНОН/01_РОЛИ"
  "00_КАНОН/02_ПРАВИЛА"
  "01_ЦЕХ/01_ЖУРНАЛЫ"
  "01_ЦЕХ/01_ЖУРНАЛЫ/АРГУС_ВХОД"
  "01_ЦЕХ/02_ЧЕРНОВИКИ"
  "01_ЦЕХ/03_СБОРКИ"
  "01_ЦЕХ/04_ЗАДАЧИ"
  "01_ЦЕХ/05_КАРАНТИН"
  "02_ПРОДУКТ/01_КОД"
  "02_ПРОДУКТ/02_ДОКИ"
  "data"
)

for dir in "${DIRS[@]}"; do
  mkdir -p "$dir"
  touch "$dir/.gitkeep"
done

