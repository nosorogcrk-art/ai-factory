#!/bin/bash
# Файл: init_prompts.sh
# Создаёт структуру каталогов и шаблоны промптов для 7 ролей.
PROMPT_DIR="00_КАНОН/ПРОМПТЫ"
mkdir -p "$PROMPT_DIR"
# Шаблон для файла промпта
create_template() {
  local role=$1
  local file="$PROMPT_DIR/${role}.md"
  if [ ! -f "$file" ]; then
    cat > "$file" <<EOF
# РОЛЬ: ${role}
## 1. ПАСПОРТ РОЛИ
*(Заполняется на основе паспорта ветки BR7)*
**Ответственный:** 
**Полномочия:**
**Границы:**
## 2. СИСТЕМНЫЙ ПРОМПТ
*(Инструкция для ИИ-агента)*
Ты — ${role}. При работе сначала обращайся к внутренним документам в 00_КАНОН/ и 01_ЦЕХ/. Если задача требует микро-агента, планируй количество шагов и не превышай лимит вызовов (бюджет).
## 3. ТЕХНИЧЕСКИЕ ЛИМИТЫ
- **Максимальное количество токенов:** 
- **Разрешённые инструменты:** 
- **Доступ к папкам:** 
## 4. ИСТОРИЯ ИЗМЕНЕНИЙ
- YYYY-MM-DD: Создан шаблон (патч P7.1.1)
EOF
    echo "Created template for ${role}"
  else
    echo "Template for ${role} already exists, skipping."
  fi
}
# Список ролей
ROLES=("ARGUS" "ARCHI" "REVA" "HEFEST" "HERMES" "MNEMOSINA" "DAEDALUS")
for role in "${ROLES[@]}"; do
  create_template "$role"
done
# Установка прав доступа (чтение для всех, запись только для владельца)
chmod -R 644 "$PROMPT_DIR"/*
chmod 755 "$PROMPT_DIR"
echo "✅ Структура промптов инициализирована."